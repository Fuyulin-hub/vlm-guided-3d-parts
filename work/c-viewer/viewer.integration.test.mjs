import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {createRequire} from 'node:module';
import {readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {syntheticBundle} from './test-fixtures.mjs';
const require=createRequire(import.meta.url);
const {chromium}=require('C:/Users/ASUS/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
test('real GLB binding, clicking, list highlighting, export, and unknown rejection', {timeout:90000}, async t => {
  const server=spawn(process.execPath,['serve.cjs'],{cwd:fileURLToPath(new URL('.',import.meta.url)),env:{...process.env,PORT:'4174'},stdio:'pipe',windowsHide:true});
  t.after(()=>server.kill());
  await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);server.once('exit',code=>reject(new Error('server exited '+code)));});
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1440,height:1100}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:4174/');
  assert.match(await page.locator('.status').innerText(),/等待/, 'no fake initial loaded state');
  await page.waitForFunction(()=>!document.getElementById('loadButton').disabled);
  await page.locator('#fileInput').setInputFiles(syntheticBundle());
  await page.waitForFunction(()=>document.querySelector('.status').textContent.includes('完成'));
  assert.equal(await page.locator('.component').count(),2);
  await page.getByRole('button',{name:/Right panel/}).click();
  assert.match(await page.locator('#partId').innerText(),/19/);
  assert.equal(await page.locator('#faceCount').innerText(),'2');
  await page.locator('#frontView').click();
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  const canvas=page.locator('#viewer canvas');const rect=await canvas.boundingBox();
  await page.mouse.click(rect.x+rect.width*.36,rect.y+rect.height*.5);
  assert.match(await page.locator('#partId').innerText(),/7/,'raycast selects the real left surface');
  const downloadPromise=page.waitForEvent('download');await page.locator('#exportBinding').click();
  const download=await downloadPromise;const report=JSON.parse(await readFile(await download.path(),'utf8'));
  assert.equal(report.stats.matchedFaces,4);assert.equal(report.meshes.length,1);
  assert.deepEqual(report.meshes[0].face_label_ids,[7,7,19,19]);
  assert.equal(report.parts.every(p=>!('label_zh' in p)&&!('label_en' in p)),true);
  assert.equal(await page.locator('#partZh').count(),0);
  await page.locator('#fileInput').setInputFiles(syntheticBundle({unknown:true}));
  await page.waitForFunction(()=>document.querySelector('.status').textContent.includes('完成'));
  assert.match(await page.locator('#bindingSummary').innerText(),/0\.00%/);
  assert.equal(await page.locator('#faceCount').innerText(),'—');
  const wrong=syntheticBundle();wrong[2].buffer=Buffer.from(JSON.stringify({output_glb_sha256:'b'.repeat(64),guidance_sha256:'a'.repeat(64)}));
  await page.locator('#fileInput').setInputFiles(wrong);
  await page.waitForFunction(()=>document.querySelector('.status').textContent.includes('失败'));
  assert.equal(await page.locator('.component').count(),0,'stale semantic labels are cleared after bad provenance');
  await page.locator('#fileInput').setInputFiles(syntheticBundle().slice(0,2));
  await page.waitForFunction(()=>document.querySelector('.status').textContent.includes('等待同源确认'));
  assert.equal(await page.locator('#exportBinding').isDisabled(),true,'unverified pairing cannot silently bind');
  await page.locator('#bindConfirmed').click();
  assert.equal(await page.locator('#exportBinding').isDisabled(),true,'explicit checkbox consent is required');
  await page.locator('#pairConfirmed').check();await page.locator('#bindConfirmed').click();
  await page.waitForFunction(()=>document.querySelector('.status').textContent==='绑定完成');
  assert.equal(await page.locator('#confidence').innerText(),'人工确认');
  await page.locator('#sampleButton').click();
  await page.waitForFunction(()=>document.querySelector('.status').textContent.includes('完成'),null,{timeout:60000});
  assert.equal(await page.locator('.component').count(),15,'r04 firetruck uses actual 15-part annotation');
  const realDownloadPromise=page.waitForEvent('download');await page.locator('#exportBinding').click();
  const realDownload=await realDownloadPromise;
  const real=JSON.parse(await readFile(await realDownload.path(),'utf8'));
  assert.equal(real.source.verification.status,'verified');
  assert.equal(real.source.glb_sha256,'536e5fe464e538eddcd5cc03d9599d7795756f5f68c9e41e17bb869f45ad0ea3');
  assert.ok(real.stats.matchedFaces>0,'real texture surfaces obtain labels');
  assert.ok(real.stats.unmatchedFaces>0,'uncertain real boundaries remain unknown');
  assert.match(await page.locator('.status').innerText(),/匹配不足/,'do not present sparse color hits as complete semantic binding');
  await realDownload.saveAs(fileURLToPath(new URL('./qa/firetruck_face_labels.json',import.meta.url)));
  const matchedLabel=Number(Object.keys(real.stats.byLabel)[0]);
  const matchedPart=real.parts.find(p=>p.label_id===matchedLabel);
  await page.locator(`.component[data-label-id="${matchedLabel}"]`).click();
  assert.ok((await page.locator('#partId').innerText()).includes(`LABEL ${matchedLabel}`));
  assert.equal(await page.locator('#partEn').innerText(),matchedPart.label);
  await page.screenshot({path:fileURLToPath(new URL('./qa/firetruck-binding.png',import.meta.url)),fullPage:true});
  console.log('REAL_FIRETRUCK_STATS',JSON.stringify(real.stats));
  assert.equal(errors.length,0,errors.join('\n'));
});
